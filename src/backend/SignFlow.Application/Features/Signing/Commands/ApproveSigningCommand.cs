using Microsoft.EntityFrameworkCore;
using Microsoft.Extensions.Logging;
using SignFlow.Application.Common.Exceptions;
using SignFlow.Application.Common.Interfaces;
using SignFlow.Application.Common.Services;
using SignFlow.Domain.Enums;

namespace SignFlow.Application.Features.Signing.Commands;

public record ApproveSigningCommand(
    string SecureToken,
    string IpAddress,
    string UserAgent) : ICommand<ApproveSigningResult>;

public record ApproveSigningResult(bool DocumentCompleted);

public class ApproveSigningCommandHandler(
    IApplicationDbContext db,
    IWorkflowEngine workflowEngine,
    IStorageService storage,
    IPdfStampService pdfStamp,
    IHtmlTemplatePdfGenerator htmlPdfGenerator,
    IAuditService auditService,
    INotificationHub hub,
    ILogger<ApproveSigningCommandHandler> logger) : ICommandHandler<ApproveSigningCommand, ApproveSigningResult>
{
    public async Task<ApproveSigningResult> HandleAsync(ApproveSigningCommand command, CancellationToken cancellationToken = default)
    {
        var recipient = await db.Recipients
            .Include(r => r.Document)
            .FirstOrDefaultAsync(r => r.SecureToken == command.SecureToken, cancellationToken)
            ?? throw new NotFoundException("Signing session not found or has expired.");

        if (recipient.Status == WorkflowStepStatus.Completed)
            throw new ConflictException("You have already approved this document.");

        if (recipient.Status == WorkflowStepStatus.Rejected)
            throw new ConflictException("You have rejected this document.");

        if (recipient.Document.IsExpired())
            throw new ConflictException("This request has expired.");

        if (recipient.ApprovalType == ApprovalType.ViewOnly)
            throw new ConflictException("View-only participants don't approve documents.");

        ReviewGateRules.Require(recipient);

        if (recipient.ApprovalType is ApprovalType.Review or ApprovalType.Approval)
        {
            var uncheckedCount = await db.ChecklistItems
                .CountAsync(c => c.RecipientId == recipient.Id && !c.IsChecked, cancellationToken);
            if (uncheckedCount > 0)
                throw new ConflictException("Please check off every checklist item before approving.");
        }

        if (recipient.Document.Status == DocumentStatus.ChangesRequested)
            throw new ConflictException("Changes have been requested on this document — it is paused until the owner uploads a revision.");

        // Post-revision the document sits in Draft while the owner re-places fields, but the
        // signing links are already circulating — block approvals until the explicit re-send.
        if (recipient.Document.Status == DocumentStatus.Draft)
            throw new ConflictException("This document is being revised by its owner and is not open for signing yet.");

        // Load the fields this recipient is responsible for. Content signers also own orphaned
        // fields (legacy documents saved before the client-ID preservation fix); reviewers and
        // approvers gate the workflow without completing fields, so they only validate fields
        // explicitly assigned to them (normally none).
        var canClaimOrphans = recipient.ApprovalType is ApprovalType.Signature or ApprovalType.Stamp;
        var allFields = await db.SignatureFields
            .Where(f => f.DocumentId == recipient.DocumentId &&
                        (f.RecipientId == recipient.Id ||
                         (canClaimOrphans &&
                          (f.RecipientId == null ||
                           !db.Recipients.Any(r => r.DocumentId == recipient.DocumentId && r.Id == f.RecipientId)))))
            .ToListAsync(cancellationToken);

        if (!RequiredFieldRules.AllRequiredSatisfied(allFields))
            throw new ConflictException("Not all required fields have been signed.");

        // The final artifact is only generated by the last required recipient still pending —
        // intermediate approvals (signer or reviewer) just advance the workflow.
        var hasSubsequentRequired = await db.Recipients
            .AnyAsync(r => r.DocumentId == recipient.DocumentId
                        && r.Order > recipient.Order
                        && r.IsRequired
                        && r.Status == Domain.Enums.WorkflowStepStatus.Pending, cancellationToken);

        if (recipient.Document.HtmlTemplateId.HasValue)
        {
            if (!hasSubsequentRequired)
            {
                // Last signer — collect ALL signatures across every recipient for this document
                var allDocFields = await db.SignatureFields
                    .Include(f => f.Signatures)
                    .Where(f => f.DocumentId == recipient.DocumentId
                             && f.IsSigned
                             && f.Signatures.Any(s => s.ImageUrl != null))
                    .ToListAsync(cancellationToken);

                // Build a name lookup so each signature block shows the correct signer
                var recipientNames = await db.Recipients
                    .Where(r => r.DocumentId == recipient.DocumentId)
                    .ToDictionaryAsync(r => r.Id, r => r.Name, cancellationToken);

                var filledValues = string.IsNullOrEmpty(recipient.Document.FilledValuesJson)
                    ? []
                    : System.Text.Json.JsonSerializer.Deserialize<Dictionary<string, string>>(
                        recipient.Document.FilledValuesJson) ?? [];

                // A field re-signed after a revision keeps its old rows as evidence; the
                // current round's signature is the latest one.
                var sigSummaries = allDocFields
                    .Select(f => (Field: f, Sig: f.Signatures.Where(s => s.ImageUrl != null).OrderByDescending(s => s.SignedAt).First()))
                    .OrderBy(x => x.Sig.SignedAt)
                    .Select(x => new HtmlTemplatePdfSignature(
                        x.Sig.ImageUrl!,
                        x.Field.RecipientId.HasValue && recipientNames.TryGetValue(x.Field.RecipientId.Value, out var n) ? n : recipient.Name,
                        x.Sig.SignedAt,
                        x.Field.TemplateKey))
                    .ToList();

                // Render the HTML template from the snapshot taken at request-creation time —
                // unaffected by the source template being edited or deleted later. This goes
                // through the same renderer as the signing screen, so the PDF being sealed here is
                // byte-identical to what the signer was shown.
                var fieldTypes = await db.HtmlTemplateFields.AsNoTracking()
                    .Where(f => f.HtmlTemplateId == recipient.Document.HtmlTemplateId!.Value)
                    .ToDictionaryAsync(f => f.FieldKey, f => f.Type, cancellationToken);

                // Each signature placeholder in the text leaves a marker; the PDF generator swaps it for that
                // signer's signature, so a signature lands where the template put it and not only at the end.
                var signatureSlots = allDocFields
                    .Where(f => !string.IsNullOrEmpty(f.TemplateKey))
                    .Select(f => f.TemplateKey!)
                    .Distinct()
                    .ToDictionary(key => key, HtmlSignatureSlots.Marker);

                var renderedHtml = HtmlContractRenderer.Render(
                    recipient.Document.HtmlContentSnapshot, filledValues, fieldTypes, signatureSlots);

                var pdfStream = await htmlPdfGenerator.GenerateAsync(
                    renderedHtml, recipient.Document.Title, sigSummaries, cancellationToken);

                var finalPath = await storage.UploadAsync(
                    pdfStream,
                    $"signed_{recipient.Document.FileName}",
                    "application/pdf",
                    $"completed/{recipient.DocumentId}",
                    cancellationToken);

                recipient.Document.SetFinalStoragePath(finalPath);
            }
        }
        else if (!hasSubsequentRequired)
        {
            // Standard PDF: stamp EVERY signed field across the whole document onto the original.
            // Stamping per-recipient here used to overwrite FinalStoragePath with only the last
            // approver's fields, erasing earlier signers' stamps from the final artifact — and a
            // reviewer/approver finishing last would have produced an empty stamp pass.
            var signedDocFields = await db.SignatureFields
                .Include(f => f.Signatures)
                .Where(f => f.DocumentId == recipient.DocumentId && f.IsSigned)
                .ToListAsync(cancellationToken);

            // Latest signature per field = the current round's (older rows are kept evidence).
            var stampDtos = signedDocFields
                .Select(f => new StampFieldDto(
                    f.FieldType, f.Page, f.X, f.Y, f.Width, f.Height,
                    f.SignedValue, f.Signatures.OrderByDescending(s => s.SignedAt).FirstOrDefault()?.ImageUrl))
                .ToList();

            var stampedStream = await pdfStamp.StampAsync(recipient.Document.StoragePath, stampDtos, cancellationToken);
            var finalPath = await storage.UploadAsync(
                stampedStream,
                $"signed_{recipient.Document.FileName}",
                "application/pdf",
                $"completed/{recipient.DocumentId}",
                cancellationToken);

            recipient.Document.SetFinalStoragePath(finalPath);
        }

        await db.SaveChangesAsync(cancellationToken);

        // Advance workflow (marks recipient Completed → next signer or document Completed)
        await workflowEngine.AdvanceAsync(recipient.DocumentId, recipient.Id, cancellationToken);
        var documentCompleted = await workflowEngine.IsCompleteAsync(recipient.DocumentId, cancellationToken);

        var auditDescription = recipient.ApprovalType switch
        {
            ApprovalType.Review => "Reviewer approved the document",
            ApprovalType.Approval => "Approver granted formal approval",
            _ => "Recipient approved and submitted signature"
        };
        var actorLabel = string.IsNullOrWhiteSpace(recipient.RoleLabel) ? null : $" ({recipient.RoleLabel})";

        await auditService.LogAsync(
            recipient.DocumentId,
            AuditAction.WorkflowStepCompleted,
            command.IpAddress,
            auditDescription + actorLabel,
            recipientId: recipient.Id,
            userAgent: command.UserAgent,
            actorName: recipient.Name,
            actorEmail: recipient.Email,
            cancellationToken: cancellationToken);

        await hub.SendToGroupAsync(
            $"document-{recipient.DocumentId}",
            "document-progress",
            new { DocumentId = recipient.DocumentId, RecipientId = recipient.Id, AllSigned = true, DocumentCompleted = documentCompleted },
            cancellationToken);

        logger.LogInformation("Recipient {RecipientId} approved signing for document {DocumentId}", recipient.Id, recipient.DocumentId);

        return new ApproveSigningResult(documentCompleted);
    }
}
